// Best-effort hadith-number markers. Tune per edition.
// Arabic-Indic (٠١٢٣٤٥٦٧٨٩) and Eastern Arabic (۰۱۲۳...) digits, and the
// common "رقم الحديث / الحديث رقم" prefixes.
const NUMBER_PATTERNS = [
  /(?:رقم\s*الحديث|الحديث\s*رقم)\s*[:：]?\s*([٠-٩0-9]+)/i,
  /^\s*([٠-٩0-9]+)\s*[-–.]\s*/m,
];

function toLatinDigits(s) {
  const map = {
    "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
    "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
    "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
    "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
  };
  return String(s).replace(/[٠-٩۰-۹]/g, (d) => map[d] ?? d);
}

function detectHadithNumber(content) {
  for (const re of NUMBER_PATTERNS) {
    const m = re.exec(content);
    if (m) return toLatinDigits(m[1]).trim();
  }
  return null;
}

