/**
 * Build the citation-addressable index (Roadmap Phase 2) from live shamela.ws
 * data. Run where network is available:
 *
 *   node scripts/build-hadith-index.mjs
 *
 * Output: rewrites `src/data/hadith-index.mjs` with a forward index
 * (`hadith_number → page`) and reverse index (`page → [numbers]`) per hadith
 * book, plus a `surah:ayah → page` map per tafsir book.
 *
 * HONEST LIMITATIONS (do not paper over these):
 *   - shamela.ws does NOT mark hadith numbers uniformly. Some editions put the
 *     number in a heading, some inline in Arabic numerals, some not at all.
 *     This script's number detection is therefore best-effort and MUST be
 *     tuned per edition (see `NUMBER_PATTERNS` / `per-edition overrides`).
 *   - Where no number is reliably detectable, entries are omitted — the index
 *     is incomplete by design, never fabricated.
 *   - Tafsir "main passage for an ayah" is approximate: a mufassir discusses an
 *     ayah in several places; this script records the first strong match.
 *
 * The list of books to index (`BOOKS`) is intentionally small to start with
 * (the high-traffic reference works from Priority 3). Expand after verifying.
 */

