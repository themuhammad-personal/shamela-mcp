const http = createHttp();
const client = createClient({ text: http.text });

const index = { generated_at: new Date().toISOString(), books: {} };

for (const [name, cfg] of Object.entries(BOOKS)) {
  console.log(`\n== indexing ${name} (${cfg.id}, ${cfg.type}) ==`);
  const d = await client.details(cfg.id);
  const nodes = d.toc.map((t) => /\/book\/\d+\/(\d+)/.exec(t.href)?.[1]).filter(Boolean);

  if (cfg.type === "hadith") {
    const forward = {};
    const reverse = {};
    for (const page of nodes) {
      const { content } = await client.bookPage(cfg.id, page);
      const num = detectHadithNumber(content);
      if (num) {
        forward[num] = { page };
        (reverse[page] ||= []).push(num);
      }
    }
    index.books[cfg.id] = { type: "hadith", index: forward, reverse };
    console.log(`  hadith: ${Object.keys(forward).length} numbered of ${nodes.length} pages`);
  } else if (cfg.type === "tafsir") {
    const ayahs = {};
    for (const page of nodes) {
      const { content } = await client.bookPage(cfg.id, page);
      const ref = detectAyah(content);
      if (ref) ayahs[ref] = { page };
    }
    index.books[cfg.id] = { type: "tafsir", ayahs };
    console.log(`  tafsir: ${Object.keys(ayahs).length} ayah refs of ${nodes.length} pages`);
  }
}

const outPath = resolve(__dirname, "../src/data/hadith-index.mjs");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `/**\n * GENERATED by scripts/build-hadith-index.mjs — do not hand-edit.\n */\nexport default ${JSON.stringify(index, null, 2)};\n`,
);
console.log(`\nWrote ${outPath}`);
